"""## 4. Pré-processamento de Imagens

Aqui é feita a implementação do pré-processamento das imagens, incluindo redimensionamento com preservação de proporção (letterbox), normalização e conversão para tensor, além da etapa inversa para mapear as bounding boxes de volta para a imagem original.
"""

def ler_classes(caminho):
  # Abre o arquivo com os nomes das classes (coco.names)
    with open(caminho) as f:
      # Remove espaços/quebras de linha e retorna lista de strings
        return [c.strip() for c in f.readlines()]

def gerar_cores(nomes_classes):
   # Cria cores distintas
    hsv = [(x / len(nomes_classes), 0.9, 0.9) for x in range(len(nomes_classes))]
    # Converte de HSV para RGB e escala para [0, 255]
    cores = [tuple(int(v*255) for v in colorsys.hsv_to_rgb(*h)) for h in hsv]
    # Embaralha as cores para evitar padrões previsíveis
    random.seed(42)
    random.shuffle(cores)
    return cores

def letterbox(image, novo_tamanho=(640, 640), cor=(114, 114, 114)):
    """
    Redimensiona a imagem mantendo a proporção original.
    O espaço restante é preenchido com a cor especificada (cinza neutro).
    Isso evita distorção geométrica que prejudicaria a detecção.
    """

    # Tamanho original
    iw, ih = image.size
    # Tamanho que queremos (ex: 640x640)
    nw, nh = novo_tamanho
    # Calcula escala mantendo proporção
    escala = min(nw / iw, nh / ih)
    # Novo tamanho redimensionado
    nw_r   = int(iw * escala)
    nh_r   = int(ih * escala)
    # Redimensiona a imagem
    img_r = image.resize((nw_r, nh_r), Image.BICUBIC)
    # Cria imagem com fundo cinza
    canvas = Image.new('RGB', novo_tamanho, cor)
    # Calcula onde colar a imagem (centralizada)
    offset_x = (novo_tamanho[0] - nw_r) // 2
    offset_y = (novo_tamanho[1] - nh_r) // 2
    # Cola a imagem redimensionada na imagem do fundo cinza
    canvas.paste(img_r, (offset_x, offset_y))
    return canvas, escala, offset_x, offset_y

def preprocessar(caminho_img, tamanho=640):
    """
    Etapas de pré-processamento da imagem:

    1. Carrega a imagem
    2. Aplica letterbox (redimensionamento + padding)
    3. Converte para array NumPy
    4. Normaliza
    5. Ajusta formato
    6. Converte para tensor PyTorch
    """
    # Carrega imagem original
    img_orig = Image.open(caminho_img).convert('RGB')
    # Aplica letterbox
    img_lb, escala, ox, oy = letterbox(img_orig, (tamanho, tamanho))
    # Converte para array e normaliza
    arr = np.array(img_lb, dtype=np.float32) / 255.0
    # Muda formato: altura/largura/canais --> canais/altura/largura
    arr = np.transpose(arr, (2, 0, 1))
     # Converte para tensor
    tensor = torch.from_numpy(arr).unsqueeze(0)

    return img_orig, tensor, escala, ox, oy

def reverter_caixas(boxes, escala, offset_x, offset_y, img_orig_size):
    """
    Converte as caixas previstas no espaço 640x640 (letterbox)
    de volta para o tamanho original da imagem.

    Passos:
    1. Remove o padding
    2. Desfaz a escala
    3. Garante que as caixas fiquem dentro da imagem
    """
    boxes = boxes.clone().float()
    # Remove deslocamento causado pelo padding
    boxes[:, [0, 2]] -= offset_x
    boxes[:, [1, 3]] -= offset_y
    # Desfaz a escala
    boxes /= escala
    # Limita coordenadas ao tamanho da imagem original
    iw, ih = img_orig_size
    boxes[:, [0, 2]] = boxes[:, [0, 2]].clamp(0, iw)
    boxes[:, [1, 3]] = boxes[:, [1, 3]].clamp(0, ih)
    return boxes
