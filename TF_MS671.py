"""## 5. Decoder das Saídas do YOLOv8

A saída do modelo para cada escala é um par `(box_feat, cls_feat)`.  
Precisamos converter isso para caixas absolutas em pixels.
"""

def gerar_grade(h, w, stride, device):
    """
    Gera a grade de pontos centrais da imagem.

    Cada ponto da grade representa o centro de uma possível detecção.
    No YOLOv8 não usamos âncoras fixas, usamos apenas esses pontos.
    """

    # Cria coordenadas (y, x) para cada posição da feature map
    gy, gx = torch.meshgrid(
        torch.arange(h, device=device),
        torch.arange(w, device=device),
        indexing='ij'
    )
    # Junta (x, y) em pares e transforma em lista
    grade = torch.stack([gx, gy], dim=-1).reshape(-1, 2).float()

    # Converte de "índice da grade" para coordenada em pixels
    # +0.5 leva do canto da célula para o centro
    return (grade + 0.5) * stride


def decodificar_saidas(outputs, img_size=640, device='cpu'):
    """
    Converte a saída bruta do modelo em bounding boxes de verdade.

    O modelo retorna:
    - distâncias em relação ao centro (via distribuição)
    - probabilidades de classe

    Aqui transformamos isso em:
    - caixas (x1, y1, x2, y2)
    - probabilidades por classe
    """
    # Stride = quanto cada célula da feature map representa na imagem original
    # Strides para cada escala: 8 (80x80), 16 (40x40), 32 (20x20)
    strides = [img_size // s for s in [80, 40, 20]]
    dfl = DFL(reg_max=16).to(device)

    todas_caixas  = []
    todas_classes = []

    for i, ((box_feat, cls_feat), stride) in enumerate(zip(outputs, strides)):
        B, _, H, W = box_feat.shape

        # Gerar grade de centros
        grade = gerar_grade(H, W, stride, device)

        # Decodifica DFL -> distâncias (dl, dt, dr, db)
        dist = dfl(box_feat).squeeze(0)
        dist = dist * stride

        # Converte para pixels reais
        dl, dt, dr, db = dist[0], dist[1], dist[2], dist[3]
        cx, cy = grade[:, 0], grade[:, 1]

        # Converte para caixas
        x1 = (cx - dl).unsqueeze(1)
        y1 = (cy - dt).unsqueeze(1)
        x2 = (cx + dr).unsqueeze(1)
        y2 = (cy + db).unsqueeze(1)
        caixas = torch.cat([x1, y1, x2, y2], dim=1)

        # Probabilidades de classe
        # YOLOv8 usa sigmoid (não softmax)
        classes = torch.sigmoid(cls_feat.squeeze(0).reshape(80, -1).T)

        todas_caixas.append(caixas)
        todas_classes.append(classes)

    # Junta todas as escalas
    todas_caixas  = torch.cat(todas_caixas,  dim=0)
    todas_classes = torch.cat(todas_classes, dim=0)

    return todas_caixas, todas_classes

"""## 6. Implementação manual do IoU e NMS

6.1. Implementação da Função manual_iou
"""

def manual_iou(box, boxes):
    """
    Calcula o IoU (Intersection over Union) entre uma caixa e várias outras.

    IoU = área da interseção / área da união

    Parâmetros:
    - box: tensor no formato [x1, y1, x2, y2]
    - boxes: tensor com várias caixas no mesmo formato
    """
    # 1. Determinar as coordenadas do retângulo de intersecção
    x1_inter = torch.max(box[0], boxes[:, 0])
    y1_inter = torch.max(box[1], boxes[:, 1])
    x2_inter = torch.min(box[2], boxes[:, 2])
    y2_inter = torch.min(box[3], boxes[:, 3])

    # 2. Calcular área da intersecção (clamp garante que não seja negativa se não houver sobreposição)
    inter_w = torch.clamp(x2_inter - x1_inter, min=0)
    inter_h = torch.clamp(y2_inter - y1_inter, min=0)
    area_intersecao = inter_w * inter_h

    # 3. Calcular áreas individuais
    area_box = (box[2] - box[0]) * (box[3] - box[1])
    area_boxes = (boxes[:, 2] - boxes[:, 0]) * (boxes[:, 3] - boxes[:, 1])

    # 4. Calcular União: Área1 + Área2 - Intersecção
    area_uniao = area_box + area_boxes - area_intersecao

    # 5. IoU
    return area_intersecao / area_uniao

"""6.2 Implementação da Função manual_nms"""

def manual_nms(boxes, scores, iou_threshold=0.45):
    """
    Nom Max Supression Manual.
    boxes: tensor de coordenadas
    scores: tensor de confianças
    iou_threshold: o limiar de sobreposição (ex: 0.45)
    """
    # Lista para guardar os índices das caixas que vamos manter
    keep = []

    # Pegar os índices ordenados pela confiança (do maior para o menor)
    vivos = torch.argsort(scores, descending=True)

    while vivos.size(0) > 0:
        # O primeiro da lista é o que tem maior confiança
        campeao = vivos[0]
        keep.append(campeao.item())

        # Se for a última caixa/indice, paramos por aqui
        if vivos.size(0) == 1:
            break

        # Calcular IoU do que tem maior confiança com todos os outros da lista
        outros = vivos[1:]
        ious = manual_iou(boxes[campeao], boxes[outros])

        # Manter apenas os que têm IoU MENOR que o limiar
        # (se for maior, significa que é o mesmo objeto e deve ser deletado)
        mascara = ious <= iou_threshold
        vivos = outros[mascara]

    return torch.tensor(keep)

"""## 7. Inferência e Visualização
Finalmente, vamos fazer o modelo detectar os objetos e mostrar o resultado na imagem.
"""

def detectar(caminho_img, modelo, class_names, device,
             score_threshold=0.25, iou_threshold=0.45,
             img_size=640, max_deteccoes=100):

    """
    Etapas da detecção de objetos:

    1. Pré-processamento da imagem
    2. Inferência com o modelo
    3. Decodificação das saídas
    4. Filtragem por confiança
    5. Aplicação de NMS
    6. Conversão para coordenadas originais
    7. Visualização dos resultados
    """
    print(f"\nProcessando: {caminho_img}")

    # 1. Pré-processamento
    img_orig, tensor, escala, ox, oy = preprocessar(caminho_img, img_size)
    tensor = tensor.to(device)

    # 2. Inferência
    modelo.eval()
    with torch.no_grad():
        outputs = modelo(tensor)

    # 3. Decodificação
    caixas, classes = decodificar_saidas(outputs, img_size, device)

    # 4. Filtragem por score de confiança
    scores_max, classes_idx = classes.max(dim=1)
    mascara = scores_max >= score_threshold
    caixas      = caixas[mascara]
    scores_max  = scores_max[mascara]
    classes_idx = classes_idx[mascara]

    print(f"  Detecções antes do NMS: {len(caixas)}")

    # Caso não haja detecções:
    if len(caixas) == 0:
        print("  Nenhum objeto detectado.")
        plt.figure(figsize=(10, 8))
        plt.imshow(img_orig)
        plt.axis('off')
        plt.title("Nenhum objeto detectado")
        plt.show()
        return

    # 5. NMS por classe (aplica NMS separadamente para cada classe)
    keep_final = []
    for cls in classes_idx.unique():
      # Seleciona apenas caixas dessa classe
        mascara_cls = classes_idx == cls
        idx_cls     = mascara_cls.nonzero(as_tuple=True)[0]
        # Aplica NMS
        keep_cls    = manual_nms(
            caixas[idx_cls], scores_max[idx_cls], iou_threshold
        )
        # Guarda índices das caixas mantidas
        keep_final.append(idx_cls[keep_cls])

    keep_final  = torch.cat(keep_final)
    # Ordena por score e limita número máximo de detecções
    ordem       = scores_max[keep_final].argsort(descending=True)[:max_deteccoes]
    keep_final  = keep_final[ordem]

    caixas_finais  = caixas[keep_final]
    scores_finais  = scores_max[keep_final]
    classes_finais = classes_idx[keep_final]

    # 6. Reverter para coordenadas da imagem original
    caixas_orig = reverter_caixas(caixas_finais, escala, ox, oy, img_orig.size)

    n = len(caixas_finais)
    print(f"  Detecções após NMS: {n}")
    print(f"  Objetos detectados:")
    for i in range(n):
        nome  = class_names[classes_finais[i].item()]
        conf  = scores_finais[i].item()
        print(f"    [{i+1:2d}] {nome:20s}  confiança: {conf:.3f}")

    # 7. Visualização
    # Desenha caixas e labels na imagem original
    img_draw = img_orig.copy()
    draw     = ImageDraw.Draw(img_draw)
    # Tenta usar uma fonte melhor
    try:
        font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 14)
    except:
        font = ImageFont.load_default()

    # Espessura da caixa proporcional ao tamanho da imagem
    espessura = max(2, (img_orig.size[0] + img_orig.size[1]) // 500)

    for i in range(n):
        x1, y1, x2, y2 = caixas_orig[i].cpu().tolist()
        cls_id = classes_finais[i].item()
        score  = scores_finais[i].item()
        nome   = class_names[cls_id]
        cor    = CORES[cls_id]

        # Bounding box
        for t in range(espessura):
            draw.rectangle([x1+t, y1+t, x2-t, y2-t], outline=cor)

        # Label
        label = f"{nome}: {score:.2f}"
        bbox_txt = draw.textbbox((x1, y1), label, font=font)
        draw.rectangle(bbox_txt, fill=cor)
        draw.text((x1, y1), label, fill=(255, 255, 255), font=font)

    # Exibição da imagem final
    plt.figure(figsize=(12, 10))
    plt.imshow(img_draw)
    plt.axis('off')
    plt.title(f"{n} objeto(s) detectado(s) — score≥{score_threshold}, IoU≤{iou_threshold}")
    plt.tight_layout()
    plt.show()

    return caixas_orig, scores_finais, classes_finais

