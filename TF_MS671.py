# Implementando a arquitetura - blocos fundamentais da arquitetura YOLOv8 em PyTorch, incluindo as camadas convolucionais,
# blocos residuais, o módulo principal (C2f), uma camada de agregação de contexto (SPPF) e o mecanismo de decodificação das bounding boxes (DFL).

class Conv(nn.Module):

    """
    Bloco base do YOLOv8: Convolução  -> BatchNorm2d -> ativação (SiLU)
    Nota: O v8 usa SiLU (Sigmoid Linear Unit) em vez do LeakyReLU do v3.
    SiLU(x) = x * sigmoid(x) — A ativação SiLU é mais suave que ReLU/LeakyReLU e melhora o aprendizado..
    """
    def __init__(self, in_c, out_c, k=1, s=1, p=None, g=1):
        super().__init__()
        # Define padding automático para manter o tamanho da imagem
        if p is None:
            p = k // 2
        self.conv = nn.Conv2d(in_c, out_c, k, s, p, groups=g, bias=False)
        self.bn   = nn.BatchNorm2d(out_c, eps=1e-3, momentum=0.03)
        self.act  = nn.SiLU(inplace=True)

    def forward(self, x):
        return self.act(self.bn(self.conv(x)))


class Bottleneck(nn.Module):
    """
    Bottleneck do YOLOv8: duas convoluções 3x3 com conexão residual opcional (skip connection).
    Diferente do v3 (que usava 1x1 -> 3x3), o v8 usa 3x3 -> 3x3, evitando perda de gradiente.
    """
    def __init__(self, in_c, out_c, shortcut=True, e=0.5):
        super().__init__()
        hidden = int(out_c * e)
        self.cv1 = Conv(in_c,   hidden, 3, 1)
        self.cv2 = Conv(hidden, out_c,  3, 1)
        # Só usa conexão residual se entrada e saída tiverem mesmo tamanho
        self.add = shortcut and (in_c == out_c)

    def forward(self, x):
        return x + self.cv2(self.cv1(x)) if self.add else self.cv2(self.cv1(x))


class C2f(nn.Module):
    """
    Bloco principal do YOLOv8.

    - Divide a informação em dois caminhos após uma convolução 1x1
    - Um deles passa por vários Bottlenecks e o resultado d ecada um é guardado
    - Junta tudo no final com uma convolução 1x1

    Isso melhora o fluxo de informação e reduz custo computacional.
    """

    def __init__(self, in_c, out_c, n=1, shortcut=True, e=0.5):
        super().__init__()
        hidden = int(out_c * e)
        self.cv1 = Conv(in_c,       2 * hidden, 1, 1)
        self.cv2 = Conv((2 + n) * hidden, out_c, 1, 1)
        # Sequência de bottlenecks
        self.m   = nn.ModuleList(
            [Bottleneck(hidden, hidden, shortcut, e=1.0) for _ in range(n)]
        )

    def forward(self, x):
        # # Divide o tensor em dois caminhos
        y = list(self.cv1(x).chunk(2, dim=1))
        # Aplica bottlenecks em sequência
        y.extend(m(y[-1]) for m in self.m)
        # Concatena todos e reduz dimensões
        return self.cv2(torch.cat(y, dim=1))


class SPPF(nn.Module):
    """
    Camada que aumenta o "campo de visão" da rede.
    Captura contexto global aplicando MaxPool de tamanho k três vezes
    sequencialmente
    (entende melhor a imagem como um todo)
    """
    def __init__(self, in_c, out_c, k=5):
        super().__init__()
        hidden = in_c // 2
        self.cv1 = Conv(in_c,      hidden, 1, 1)
        self.cv2 = Conv(hidden * 4, out_c, 1, 1)
        self.m   = nn.MaxPool2d(k, stride=1, padding=k // 2)

    def forward(self, x):
        x  = self.cv1(x)
        y1 = self.m(x)
        y2 = self.m(y1)
        return self.cv2(torch.cat([x, y1, y2, self.m(y2)], dim=1))


class DFL(nn.Module):
    """
    Camada de decodificação das caixas:
    Converte a saída do modelo em coordenadas de bounding boxes.
    Em vez de prever diretamente os valores das caixas,
    o modelo prevê distribuições de probabilidade.

    Aqui transformamos essas distribuições em valores finais
    usando o valor esperado.
    Isso é equivalente a uma conv 1x1 com pesos fixos [0, 1, ..., reg_max-1]
    aplicada após o softmax
    """

    def __init__(self, reg_max=16):
        super().__init__()
        self.reg_max = reg_max
        # Pesos fixos: [0, 1, 2, ..., reg_max-1]
        # Não queremos que esses pesos sejam treinados.
        self.conv = nn.Conv2d(reg_max, 1, 1, bias=False)
        self.conv.weight.data = torch.arange(
            reg_max, dtype=torch.float32
        ).reshape(1, reg_max, 1, 1)
        self.conv.weight.requires_grad_(False)

    def forward(self, x):
        B, C, H, W = x.shape
        # Separa as 4 distribuições (top, bottom, left, right)
        x = x.view(B, 4, self.reg_max, H * W)
        x = x.permute(0, 3, 1, 2)
        x = F.softmax(x, dim=-1)
        x = x.permute(0, 2, 3, 1)
        x = x.reshape(B * 4, self.reg_max, 1, H * W)
        # Calcula valor esperado --> coordenada final
        return self.conv(x).reshape(B, 4, H * W)

"""No chunck abaixo, os blocos implementados anteriormente são conectados e é montada a arquitetura completa do YOLOv8-nano, definindo o fluxo de dados desde a imagem de entrada até as previsões finais."""

class DetectHead(nn.Module):
    """
    Detecção do YOLO:

    Para cada escala da imagem, o modelo prevê:
    - caixas (bounding boxes)
    - classes dos objetos

    Diferenças importantes:
    - Regressão (caixas) e classificação são feitas em ramos separados
    - Não há "objectness score", a confiança final é só a probabilidade de classe
    - As caixas são previstas via distribuição, não diretamente (por coordenadas)
    """

    def __init__(self, num_classes=80, ch=()):  # ch = canais de entrada de cada escala
        super().__init__()
        self.nc       = num_classes
        self.reg_max  = 16
        self.no       = num_classes + self.reg_max * 4
        self.nl       = len(ch)        # número de escalas (3)
        self.stride   = torch.zeros(self.nl)

        # Define número de canais internos dos ramos
        reg_ch = max(16, self.reg_max * 4, ch[0] // 4)
        cls_ch = max(num_classes, ch[0])

        # Previsão das caixas
        self.cv2 = nn.ModuleList(
            nn.Sequential(Conv(c, reg_ch, 3), Conv(reg_ch, reg_ch, 3),
                          nn.Conv2d(reg_ch, 4 * self.reg_max, 1)) for c in ch
        )
        # Previsão das classes
        self.cv3 = nn.ModuleList(
            nn.Sequential(Conv(c, cls_ch, 3), Conv(cls_ch, cls_ch, 3),
                          nn.Conv2d(cls_ch, num_classes, 1)) for c in ch
        )
        self.dfl = DFL(self.reg_max)

    def forward(self, feats):
        # Para cada escala, gera: features de caixa e features de classe
        outputs = []
        for i, x in enumerate(feats):
            box_feat = self.cv2[i](x)
            cls_feat = self.cv3[i](x)
            outputs.append((box_feat, cls_feat))
        return outputs


class YOLOv8n(nn.Module):
    """
    Implementação completa do YOLOv8-nano.

    O modelo é dividido em:
    - Backbone: extrai características da imagem
    - Neck: combina informações em múltiplas escalas
    - Head: faz as previsões finais

    A versão "nano" é menor e mais leve (menos canais e menos camadas).
    """

    def __init__(self, num_classes=80):
        super().__init__()
        # Para nano: width=0.25, depth=0.33
        # Canais base: [64, 128, 256, 512] escalados por 0.25 = [16, 32, 64, 128]
        # Repetições base: [3, 6, 6, 3] escaladas por 0.33 = [1, 2, 2, 1]

        # Extração de features (backbone)
        self.model = nn.Sequential(
            # Entrada 3ch --> 16ch
            Conv(3, 16, 3, 2), # reduz a resolução pela metade
            Conv(16, 32, 3, 2),  # reduz novamente
            C2f(32, 32, n=1, shortcut=True),

            Conv(32, 64, 3, 2), # objetos pequenos
            C2f(64, 64, n=2, shortcut=True),

            Conv(64, 128, 3, 2), # objetos médios
            C2f(128, 128, n=2, shortcut=True),

            Conv(128, 256, 3, 2), # objetos grandes
            C2f(256, 256, n=1, shortcut=True),

            SPPF(256, 256, k=5), # contexto global
        )

        # Combinação de escalas (neck)
        # de features profundas para rasas (top-down)
        self.up1  = nn.Upsample(scale_factor=2, mode='nearest')
        self.c2f_p4_td = C2f(256 + 128, 128, n=1, shortcut=False)

        self.up2  = nn.Upsample(scale_factor=2, mode='nearest')
        self.c2f_p3_td = C2f(128 + 64, 64, n=1, shortcut=False)

        # refinamento (bottom-up)
        self.down1     = Conv(64, 64, 3, 2)
        self.c2f_p4_bu = C2f(64 + 128, 128, n=1, shortcut=False)

        self.down2     = Conv(128, 128, 3, 2)                     # P4 40->20
        self.c2f_p5_bu = C2f(128 + 256, 256, n=1, shortcut=False)

        # previsões finais
        self.head = DetectHead(num_classes, ch=(64, 128, 256))

    def forward(self, x):
        # Backbone
        for i, layer in enumerate(self.model):
            x = layer(x)
            # Salvamos três níveis de feature maps
            if i == 4:  p3 = x   # 80x80, 64ch
            if i == 6:  p4 = x   # 40x40, 128ch
            if i == 9:  p5 = x   # 20x20, 256ch  (após SPPF)

        # Neck top-down
        x      = self.up1(p5)                           # 40x40
        x      = self.c2f_p4_td(torch.cat([x, p4], 1)) # funde com P4
        p4_out = x                                       # salva para bottom-up

        x      = self.up2(x)                            # 80x80
        x      = self.c2f_p3_td(torch.cat([x, p3], 1)) # funde com P3
        p3_out = x                                       # saída P3 do neck

        # Neck bottom-up
        x      = self.down1(p3_out)                          # 40x40
        x      = self.c2f_p4_bu(torch.cat([x, p4_out], 1))  # funde com P4
        p4_fin = x

        x      = self.down2(p4_fin)                          # 20x20
        p5_fin = self.c2f_p5_bu(torch.cat([x, p5], 1))      # funde com P5

        # Head
        return self.head([p3_out, p4_fin, p5_fin])

