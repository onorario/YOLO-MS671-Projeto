def carregar_pesos_yolov8(caminho_pt, modelo):

    """
    Carrega os pesos do modelo YOLOv8 oficial (Ultralytics)
    para a nossa implementação manual em PyTorch.

    Como as duas implementações têm nomes diferentes para as camadas,
    precisamos mapear manualmente esses nomes.
    """
    # Carrega o checkpoint completo
    ckpt  = torch.load(caminho_pt, map_location='cpu', weights_only=False)
    # Extrai apenas os pesos do modelo original
    src   = ckpt['model'].state_dict()

    # Mapeamento dos nomes das camadas: nome_ultralytics -> nome_no_nosso_modelo
    mapa = {
        # BACKBONE
        'model.0.':  'model.0.',
        'model.1.':  'model.1.',
        'model.2.':  'model.2.',
        'model.3.':  'model.3.',
        'model.4.':  'model.4.',
        'model.5.':  'model.5.',
        'model.6.':  'model.6.',
        'model.7.':  'model.7.',
        'model.8.':  'model.8.',
        'model.9.':  'model.9.',
        # NECK top-down
        'model.12.': 'c2f_p4_td.',
        'model.15.': 'c2f_p3_td.',
        # NECK bottom-up
        'model.16.': 'down1.',
        'model.18.': 'c2f_p4_bu.',
        'model.19.': 'down2.',
        'model.21.': 'c2f_p5_bu.',
        # HEAD
        'model.22.cv2.': 'head.cv2.', # caixas
        'model.22.cv3.': 'head.cv3.', # classe
        'model.22.dfl.': 'head.dfl.', # distribuição
    }

    dst = {} # novo dicionário com nomes compatíveis com nosso modelo
    nao_mapeado = []  # lista de pesos que não conseguimos mapear

    # Percorre todos os pesos do modelo original
    for k_src, v in src.items():
        k_dst = None
        for prefixo_src, prefixo_dst in mapa.items():
            if k_src.startswith(prefixo_src):
              # Substitui o prefixo pelo equivalente no nosso modelo
                k_dst = k_src.replace(prefixo_src, prefixo_dst, 1)
                break

        # Se conseguiu mapear, adiciona ao novo dicionário. Caso contrário, guarda como não mapeado.
        if k_dst is not None:
            dst[k_dst] = v
        else:
            nao_mapeado.append(k_src)

    # Carregar os pesos no nosso modelo:
    # strict=False permite carregar parcialmente (caso algo não bata exatamente)
    resultado = modelo.load_state_dict(dst, strict=False)
    print(f"Pesos carregados: {len(dst)}/{len(src)}")

    # Diagnóstico (para evitar bugs)
    # Pesos que o nosso modelo esperava mas não encontrou
    if resultado.missing_keys:
        print(f"  Faltando no nosso modelo ({len(resultado.missing_keys)}):")
        for k in resultado.missing_keys[:10]:
            print(f"    {k}")
    # Pesos que vieram mas não são usados no nosso modelo
    if resultado.unexpected_keys:
        print(f"  Inesperados ({len(resultado.unexpected_keys)}): (geralmente são strides/anchors internos)")
    # Pesos do modelo original que não conseguimos mapear
    if nao_mapeado:
        print(f"  Não mapeados do source ({len(nao_mapeado)}):")
        for k in nao_mapeado[:5]:
            print(f"    {k}")
    return modelo

