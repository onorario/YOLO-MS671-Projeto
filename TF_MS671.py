"""## 2. Arquitetura YOLOv8 — Implementação

O YOLOv8 é composto por três partes principais, sendo elas:
1. Extração de características da imagem (como bordas, formas e padrões mais complexos).
2. Combinação dessas informações em diferentes escalas, permitindo detectar tanto objetos pequenos quanto grandes.
3. Uso dessas features para prever onde estão os objetos (bounding boxes) e quais são suas classes.

### Diferença principal em relação ao YOLOv3:
- Uso de blocos mais modernos (C2f) no lugar dos blocos residuais antigos, melhorando a extração de características.
- As caixas não são previstas diretamente, o modelo estima uma distribuição de possíveis posições (DFL) e calcula o valor final a partir dela, o que aumenta a precisão.
- A saída é desacoplada, ou seja, uma parte do modelo prevê a presença de objeto, enquanto outra prevê a classe, tornando o processo mais eficiente.
"""

